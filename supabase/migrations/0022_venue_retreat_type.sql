-- Issue #288 — palier 1 (additif, sans régression, zéro impact runtime).
--
-- `retraites` en V1 = overlay éditorial (data/spots-retraites.js, 394 entrées)
-- re-taguant des spots DÉJÀ présents en V2 (matchés par external_id). Ce n'est
-- pas un import de lieux mais un TAG transverse : une venue garde sa famille
-- d'origine (fitness/raquette/yoga…) ET peut être une retraite.
--
-- Modèle décidé (Gautier) : tag, pas déplacement ni doublon.
--
-- Cette migration ajoute la colonne nullable `retreat_type` + un index partiel,
-- et backfill les 393/394 venues matchées par external_id (la non-matchée
-- no-op silencieusement). AUCUN code ne lit encore la colonne → 0 impact
-- runtime. Le câblage du filtre famille `retraites` = palier 2 (ticket séparé).
--
-- Valeurs de retreat_type : surf_camp, fitness_bootcamp, tennis_camp,
-- wellness_retreat, yoga_retreat.
-- ════════════════════════════════════════════════════════════════════════

ALTER TABLE venue ADD COLUMN IF NOT EXISTS retreat_type TEXT;

COMMENT ON COLUMN venue.retreat_type IS
  'Tag transverse « retraite/camp » (issue #288). NULL = pas une retraite. Valeurs : surf_camp, fitness_bootcamp, tennis_camp, wellness_retreat, yoga_retreat. La venue conserve sa family_slug d''origine.';

-- Index partiel : seules les venues taguées (≈393) sont indexées → léger.
-- Servira au palier 2 (filtre famille retraites = retreat_type IS NOT NULL).
CREATE INDEX IF NOT EXISTS idx_venue_retreat_type
  ON venue (retreat_type)
  WHERE retreat_type IS NOT NULL;

